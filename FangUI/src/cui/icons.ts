export const ICON_NAMES: string[] = Object.keys(ICONS);

/** 图标名 → 内联 SVG。找不到就返回空串。 */
export function iconSvg(name: string): string {
  const def = ICONS[name.trim()];
  if (!def) return '';
  const extra = EXTRA[name.trim()] ?? '';
  return (
    `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" ` +
    `stroke-width="${def.width ?? 1.5}" stroke-linecap="round" stroke-linejoin="round">` +
    `<path d="${def.d}"/>${extra}</svg>`
  );
}

/** 把界面上所有带 data-icon 的元件填上图形（已经填过的跳过）。
 *  预览、教程、AOT 产物三处共用，图标只在这一处定义。 */
export function applyIcons(doc: Document | Element): void {
  const nodes = Array.from(doc.querySelectorAll('[data-icon]'));
  for (const el of nodes) {
    if (el.querySelector('svg')) continue;
    const svg = iconSvg(el.getAttribute('data-icon') ?? '');
    if (svg) el.innerHTML = svg;
  }
}
